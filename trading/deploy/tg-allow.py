#!/usr/bin/env python3
"""Telegram-controlled IP allowlist for the HamuBot dashboard gate.

Runs from cron once a minute. Only messages from the owner's own chat id in the
bot config are honoured, so the bot's chat is the only key that can widen access.

Commands (from that chat only):
    /allow 1.2.3.4        add an address (CIDR like 1.2.3.0/24 also accepted)
    /allow                show the current list
    /deny 1.2.3.4         remove an address
    /allowall             empty the list, back to "password is enough"
    /help                 list the commands

An empty allowlist means every address is allowed through to the password gate.
A non-empty one makes nginx refuse everything not listed. Blocked addresses are
reported back with the exact command that lets them in, so a phone whose carrier
changed its IP never has to know what its address is.
"""
import ipaddress
import json
import os
import subprocess
import sys
import time
from urllib.parse import urlencode
from urllib.request import Request, urlopen

CONF = '/opt/freqtrade/user_data/config.json'
DIR = '/opt/freqtrade/ui-gate'
LIST_PATH = os.path.join(DIR, 'allowlist.txt')
NGINX_PATH = os.path.join(DIR, 'allow.conf')
STATE_PATH = '/var/lib/hamu-tg-admin.json'
CONTAINER = 'hamu-ui-gate'
REPORT_TTL = 3600

HELP = (
    "Dashboard access commands:\n"
    "/allow 1.2.3.4 - let this address in (CIDR also works)\n"
    "/allow - show the current list\n"
    "/deny 1.2.3.4 - remove an address\n"
    "/allowall - empty the list, password alone is enough again\n"
    "An empty list lets everyone reach the password box."
)


def load_state():
    try:
        with open(STATE_PATH) as fh:
            return json.load(fh)
    except Exception:
        return {'offset': None, 'reported': {}}


def save_state(state):
    tmp = STATE_PATH + '.tmp'
    with open(tmp, 'w') as fh:
        json.dump(state, fh)
    os.chmod(tmp, 0o600)
    os.replace(tmp, STATE_PATH)


def entries():
    try:
        with open(LIST_PATH) as fh:
            return [line.strip() for line in fh if line.strip()]
    except FileNotFoundError:
        return []


def rebuild():
    """Rewrite the nginx include and make the running gate pick it up."""
    items = entries()
    body = ['# generated by hamu-tg-admin.py, do not edit by hand\n']
    body += ['allow %s;\n' % item for item in items]
    if items:
        body.append('deny all;\n')
    with open(NGINX_PATH, 'w') as fh:
        fh.write(''.join(body))
    os.chmod(NGINX_PATH, 0o644)
    subprocess.run(['docker', 'exec', CONTAINER, 'nginx', '-s', 'reload'],
                   capture_output=True, text=True)


def write_entries(items):
    with open(LIST_PATH, 'w') as fh:
        fh.write('\n'.join(items) + ('\n' if items else ''))
    os.chmod(LIST_PATH, 0o644)
    rebuild()


def normalise(text):
    """Canonical form of an address, so one device cannot be listed twice.

    A bare address and its /32 form must collapse to the same string, otherwise
    /allow twice adds a duplicate and /deny fails to match what /allow stored.
    """
    text = text.strip()
    try:
        if '/' in text:
            net = ipaddress.ip_network(text, strict=False)
            if net.prefixlen == net.max_prefixlen:
                return str(net.network_address)
            return str(net)
        return str(ipaddress.ip_address(text))
    except ValueError:
        return None


def is_allowed(ip, items):
    try:
        addr = ipaddress.ip_address(ip)
    except ValueError:
        return False
    for item in items:
        try:
            if addr in ipaddress.ip_network(item, strict=False):
                return True
        except ValueError:
            continue
    return False


def tg(token, method, params):
    data = urlencode(params).encode()
    req = Request('https://api.telegram.org/bot%s/%s' % (token, method), data)
    with urlopen(req, timeout=25) as resp:
        return json.loads(resp.read().decode())


def handle(text, items):
    """Return (reply, new_items) for one owner message."""
    parts = text.split()
    cmd = parts[0].lower().lstrip('/').split('@')[0]
    args = parts[1:]

    if cmd in ('help', 'start'):
        return HELP, items

    if cmd == 'allowall':
        return 'Allowlist emptied. The password alone gates the dashboard again.', []

    if cmd == 'allow':
        if not args:
            if not items:
                return 'Allowlist is empty: every address may reach the password box.', items
            return 'Allowed now:\n' + '\n'.join(items), items
        target = normalise(args[0])
        if not target:
            return 'Not an address I understand: %s' % args[0], items
        if target not in items:
            items = items + [target]
        return ('Allowed %s. %d address(es) on the list; everything else is refused.'
                % (target, len(items))), items

    if cmd == 'deny':
        if not args:
            return 'Usage: /deny 1.2.3.4', items
        target = normalise(args[0])
        if not target or target not in items:
            return '%s is not on the list.' % args[0], items
        items = [item for item in items if item != target]
        return ('Removed %s. %d address(es) left.' % (target, len(items))), items

    return None, items


def blocked_reports(items, state):
    """Report addresses the gate refused, so the owner can allow them by reply."""
    if not items:
        return []
    log = subprocess.run(['docker', 'logs', '--since', '16m', CONTAINER],
                         capture_output=True, text=True).stdout
    now = time.time()
    reports = []
    for line in log.splitlines():
        fields = line.split()
        if len(fields) < 4 or '" 403 ' not in line:
            continue
        ip = fields[0]
        if is_allowed(ip, items):
            continue
        if now - state['reported'].get(ip, 0) < REPORT_TTL:
            continue
        state['reported'][ip] = now
        reports.append('A device at %s tried to open the dashboard and the allowlist '
                       'refused it. Reply /allow %s to let it in.' % (ip, ip))
    # forget old reports so the state file stays small
    state['reported'] = {ip: seen for ip, seen in state['reported'].items()
                         if now - seen < REPORT_TTL * 24}
    return reports


def main():
    rebuild_only = '--rebuild' in sys.argv[1:]
    if rebuild_only:
        rebuild()
        print('rebuilt %s with %d entries' % (NGINX_PATH, len(entries())))
        return

    with open(CONF) as fh:
        cfg = json.load(fh)
    token = cfg['telegram']['token']
    chat = str(cfg['telegram']['chat_id'])

    state = load_state()
    # Anything the owner sent before this script first ran is history, not a
    # command; comparing dates rather than update ids keeps the very first real
    # /allow command from being swallowed when there is no backlog to seed from.
    if 'since' not in state:
        state['since'] = int(time.time())

    params = {'timeout': 0, 'allowed_updates': json.dumps(['message'])}
    if state.get('offset') is not None:
        params['offset'] = state['offset']
    updates = tg(token, 'getUpdates', params).get('result', [])

    replies = []
    for update in updates:
        state['offset'] = update['update_id'] + 1
        message = update.get('message') or {}
        if int(message.get('date') or 0) < state['since']:
            continue  # sent before the poller existed
        if str((message.get('chat') or {}).get('id')) != chat:
            continue  # not the owner: ignore entirely, no reply, no oracle
        text = (message.get('text') or '').strip()
        if not text.startswith('/'):
            continue
        items = entries()
        reply, items = handle(text, items)
        if reply is None:
            continue
        if items != entries():
            write_entries(items)
        replies.append(reply)

    replies += blocked_reports(entries(), state)
    for reply in replies:
        try:
            tg(token, 'sendMessage', {'chat_id': chat, 'text': reply})
        except Exception as headsup:
            print('send failed: %s' % headsup)

    save_state(state)
    print('%s processed %d update(s), %d repl(y/ies), list has %d entry(ies)'
          % (time.strftime('%Y-%m-%d %H:%M:%SZ', time.gmtime()),
             len(updates), len(replies), len(entries())))


if __name__ == '__main__':
    main()
